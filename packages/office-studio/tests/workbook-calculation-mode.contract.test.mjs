import assert from 'node:assert/strict'
import { afterAll, beforeAll, test } from 'vitest'
import { resolve } from 'node:path'
import { createServer } from 'vite'

let server
let apiModule

beforeAll(async () => {
  server = await createServer({ configFile: resolve(process.cwd(), 'vite.config.ts'), root: process.cwd(), server: { middlewareMode: true, hmr: false }, appType: 'custom', logLevel: 'error' })
  apiModule = await server.ssrLoadModule('/packages/office-studio/src/index.ts')
})

afterAll(async () => { await server?.close() })

test('statistical aggregates update references through content history and manual saved reopening', () => {
  const studio = new apiModule.OfficeStudio()
  const workbook = apiModule.FOffice.newAPI(studio).createWorkbook({ sheets: [{ id: 'sheet-1', name: 'Sheet1' }] })
  const sheet = workbook.getActiveSheet()
  sheet.getRange('A1:C1').setValues([[2, 4, 4]])
  const formulas = [['=AVEDEV(A1:C1)', '=DEVSQ(A1:C1)', '=GEOMEAN(A1:C1)', '=HARMEAN(A1:C1)', '=MODE.SNGL(A1:C1)']]
  sheet.getRange('D1:H1').setValues(formulas)
  const original = [8 / 9, 8 / 3, 32 ** (1 / 3), 3, 4]
  const changed = [16 / 9, 32 / 3, 128 ** (1 / 3), 4.8, 4]
  const assertValues = (range, expected) => range.getValues()[0].forEach((value, index) => assert.ok(Math.abs(value - expected[index]) < 1e-12))
  assertValues(sheet.getRange('D1:H1'), original)
  sheet.getRange('A1').setValue(8)
  assertValues(sheet.getRange('D1:H1'), changed)
  workbook.undo()
  assertValues(sheet.getRange('D1:H1'), original)
  workbook.redo()
  assertValues(sheet.getRange('D1:H1'), changed)
  workbook.setCalculationMode('manual')
  sheet.getRange('A1').setValue(2)
  assertValues(sheet.getRange('D1:H1'), changed)
  const reopened = new apiModule.OfficeStudio({ workbook: workbook.save() })
  const restoredWorkbook = apiModule.FOffice.newAPI(reopened).getActiveWorkbook()
  const restored = restoredWorkbook.getActiveSheet()
  assert.equal(restoredWorkbook.getCalculationMode(), 'manual')
  assert.deepEqual(restored.getRange('D1:H1').getFormulas(), formulas)
  assertValues(restored.getRange('D1:H1'), changed)
  restoredWorkbook.recalculate()
  assertValues(restored.getRange('D1:H1'), original)
  restoredWorkbook.setCalculationMode('automatic')
  restored.getRange('C1').setValue('=1/0')
  assert.deepEqual(restored.getRange('D1:H1').getValues(), [Array(5).fill('#DIV/0!')])
  studio.dispose()
  reopened.dispose()
})

test('statistical aggregates retain numeric text and format identity across edits, undo and saved reopening', () => {
  const studio = new apiModule.OfficeStudio()
  const workbook = apiModule.FOffice.newAPI(studio).createWorkbook({
    sheets: [{ id: 'sheet-1', name: 'Sheet1', cellData: { 0: { 0: { v: 2 }, 1: { v: '4', t: 1 }, 2: { v: 4 } } } }],
  })
  const sheet = workbook.getActiveSheet()
  const formulas = [['=AVEDEV(A1:C1)', '=DEVSQ(A1:C1)', '=GEOMEAN(A1:C1)', '=HARMEAN(A1:C1)', '=MODE.SNGL(A1:C1)']]
  sheet.getRange('D1:H1').setValues(formulas)
  assert.equal(sheet.getRange('D1').getValue(), 1)
  assert.ok(Math.abs(sheet.getRange('E1').getValue() - 8 / 3) < 1e-12)
  assert.ok(Math.abs(sheet.getRange('F1').getValue() - 32 ** (1 / 3)) < 1e-12)
  assert.equal(sheet.getRange('G1').getValue(), 3)
  assert.equal(sheet.getRange('H1').getValue(), '#N/A')
  sheet.getRange('B1').setValue(4)
  assert.ok(Math.abs(sheet.getRange('D1').getValue() - 8 / 9) < 1e-12)
  assert.equal(sheet.getRange('H1').getValue(), 4)
  workbook.undo()
  assert.equal(sheet.getRange('B1').getValue(), '4')
  assert.equal(sheet.getRange('D1').getValue(), 1)
  assert.equal(sheet.getRange('H1').getValue(), '#N/A')
  workbook.redo()
  sheet.getRange('B1').setNumberFormat('@@@')
  assert.equal(sheet.getRange('D1').getValue(), 1)
  assert.equal(sheet.getRange('H1').getValue(), '#N/A')
  const reopened = new apiModule.OfficeStudio({ workbook: workbook.save() })
  const restored = apiModule.FOffice.newAPI(reopened).getActiveWorkbook().getActiveSheet()
  assert.deepEqual(restored.getRange('D1:H1').getFormulas(), formulas)
  assert.equal(restored.getRange('D1').getValue(), 1)
  assert.equal(restored.getRange('H1').getValue(), '#N/A')
  assert.ok(Math.abs(restored.getRange('E1').getValue() - 8 / 3) < 1e-12)
  studio.dispose()
  reopened.dispose()
})

