export const SHEET_COMMON_FUNCTION_CATALOG: readonly SheetFunctionEntry[] = [
  'SUMIF', 'SUM', 'AVERAGE', 'IF', 'COUNT', 'SIN', 'MAX',
].map(name => SHEET_FUNCTION_CATALOG.find(entry => entry.name === name)!)

export function buildSheetFunctionFormula(name: string, argumentsText: string): string {
  if (!SHEET_FUNCTION_CATALOG.some(entry => entry.name === name)) throw new Error('请选择当前函数目录中的函数。')
  if (!argumentsText.trim() && !['TRUE', 'FALSE', 'NOW', 'TODAY', 'NA', 'PI', 'RAND', 'SHEET', 'SHEETS'].includes(name)) throw new Error('请输入函数参数或单元格区域。')
  const formula = `=${name}(${argumentsText.trim()})`
  try { parseFormula(formula) } catch { throw new Error('参数语法无效，请检查括号、引号和单元格引用。') }
  return formula
}
