import type { ECharts, EChartsOption } from 'echarts'
import type GlobalModel from 'echarts/types/src/model/Global.js'
import type SeriesModel from 'echarts/types/src/model/Series.js'
import type ComponentModel from 'echarts/types/src/model/Component.js'
import type ChartView from 'echarts/types/src/view/Chart.js'
import type ComponentView from 'echarts/types/src/view/Component.js'
import type { ChartVector } from './chart-geometry'
import type { RenderRect } from '../../rendering/contracts'
import { chartNativeLegendHit, chartNativeLegendNames } from './echarts-legend'
import { chartCanvasElementAsSeries, chartCanvasElementKey, clipChartCanvasPolygon, readChartCanvasElement, type ChartCanvasElement,
  type ChartCanvasElementRuntime, type ChartCanvasElementTarget } from './chart-element-interaction'

type PaintedElement = ReturnType<ReturnType<ECharts['getZr']>['storage']['getDisplayList']>[number]
type NativeElement = Parameters<Parameters<ReturnType<SeriesModel['getData']>['eachItemGraphicEl']>[0]>[0]
interface NativeChartAccess {
  getModel(): GlobalModel
  getViewOfSeriesModel(model: SeriesModel): ChartView
  getViewOfComponentModel(model: ComponentModel): ComponentView
}

/** ECharts 6.1 keeps these runtime methods out of its public d.ts. The
 * version-bound adapter checks the three methods before using their concrete
 * shipped model/view types. This is confined to painted geometry and never
 * determines author identity or writes a model. */
function nativeAccess(instance: ECharts): NativeChartAccess {
  const candidate: unknown = instance
  if (!candidate || typeof candidate !== 'object' || !('getModel' in candidate) || typeof candidate.getModel !== 'function'
    || !('getViewOfSeriesModel' in candidate) || typeof candidate.getViewOfSeriesModel !== 'function'
    || !('getViewOfComponentModel' in candidate) || typeof candidate.getViewOfComponentModel !== 'function')
    throw new Error('当前 ECharts 版本不提供已核对的图表元素几何接口。')
  return candidate as NativeChartAccess
}
function record(value: unknown): Record<string, unknown> | undefined {
  return value && typeof value === 'object' && !Array.isArray(value) ? value as Record<string, unknown> : undefined
}
function graphicElements(option: EChartsOption): Map<string, ChartCanvasElement> {
  const result = new Map<string, ChartCanvasElement>()
  const visit = (value: unknown): void => {
    if (!Array.isArray(value)) return
    for (const input of value) {
      const element = record(input)
      if (!element) continue
      visit(element.children)
      const metadata = readChartCanvasElement(record(element.info)?.officeChartElement)
      // This metadata is generated by chartGraphics, not inferred from text.
      if (typeof element.id === 'string' && metadata) result.set(element.id, metadata)
    }
  }
  const graphic = option.graphic
  if (Array.isArray(graphic)) for (const item of graphic) visit(item.elements)
  else visit(graphic?.elements)
  return result
}
function parentElement(element: NativeElement): NativeElement | undefined {
  return element.__hostTarget ?? element.parent ?? undefined
}
function transformedPolygon(element: NativeElement): ChartVector[] {
  const box = element.getBoundingRect(), transform = element.getComputedTransform()
  const points = [{ x: box.x, y: box.y }, { x: box.x + box.width, y: box.y },
    { x: box.x + box.width, y: box.y + box.height }, { x: box.x, y: box.y + box.height }]
  if (transform) for (const point of points) {
    const x = point.x, y = point.y
    point.x = transform[0] * x + transform[2] * y + transform[4]
    point.y = transform[1] * x + transform[3] * y + transform[5]
  }
  return points.every(point => Number.isFinite(point.x) && Number.isFinite(point.y)) ? points : []
}
export function transformedBounds(element: PaintedElement, frame: RenderRect): RenderRect | undefined {
  let points = transformedPolygon(element)
  for (const clip of element.__clipPaths ?? []) {
    // The native Cartesian plot and scrolling legend use rect clip paths.
    // Other path shapes retain their exact native contain() hit; their
    // selection outline is conservatively clipped by transformed bounds.
    points = clipChartCanvasPolygon(points, transformedPolygon(clip))
    if (!points.length) return undefined
  }
  points = clipChartCanvasPolygon(points, [{ x: frame.x, y: frame.y }, { x: frame.x + frame.width, y: frame.y },
    { x: frame.x + frame.width, y: frame.y + frame.height }, { x: frame.x, y: frame.y + frame.height }])
  if (!points.length) return undefined
  let left = Math.max(frame.x, Math.min(...points.map(point => point.x))), top = Math.max(frame.y, Math.min(...points.map(point => point.y)))
  let right = Math.min(frame.x + frame.width, Math.max(...points.map(point => point.x))), bottom = Math.min(frame.y + frame.height, Math.max(...points.map(point => point.y)))
  if (right < left || bottom < top) return undefined
  // Thin paths retain their actual hit test; padding only makes selection visible.
  if (right - left < 2) { left = Math.max(frame.x, left - 1); right = Math.min(frame.x + frame.width, right + 1) }
  if (bottom - top < 2) { top = Math.max(frame.y, top - 1); bottom = Math.min(frame.y + frame.height, bottom + 1) }
  return { x: left, y: top, width: right - left, height: bottom - top }
}
function union(a: RenderRect | undefined, b: RenderRect): RenderRect {
  if (!a) return { ...b }
  const x = Math.min(a.x, b.x), y = Math.min(a.y, b.y)
  return { x, y, width: Math.max(a.x + a.width, b.x + b.width) - x, height: Math.max(a.y + a.height, b.y + b.height) - y }
}

/** A frame-owned index of the real painted displayables. findHover supplies
 * z-order, native line/sector containment and clipping; selection bounds are
 * measured from the same frame rather than estimated label lengths. */
export class ChartNativeElementIndex {
  private readonly descriptors = new WeakMap<object, ChartCanvasElement>()
  private readonly targets = new Map<string, ChartCanvasElementTarget>()
  private readonly seriesMarks = new Map<string, ChartCanvasElement>()
  constructor(private readonly instance: ECharts, option: EChartsOption, runtime: ChartCanvasElementRuntime, width: number, height: number) {
    const native = nativeAccess(instance), model = native.getModel(), authoredGraphics = graphicElements(option)
    for (const entry of runtime.series) if ('binding' in entry && entry.seriesMark)
      this.seriesMarks.set(entry.binding.seriesId, { kind: 'mark', directEdit: entry.seriesMark })
    for (const entry of runtime.series) if ('items' in entry) for (const item of entry.items)
      if (item?.kind === 'mark' && item.directEdit.kind === 'seriesStyle') this.seriesMarks.set(item.directEdit.binding.seriesId, item)
    for (const axis of runtime.axes) {
      const component = model.getComponent(axis.component, axis.index)
      if (!component) continue
      native.getViewOfComponentModel(component).group.traverse(element => {
        const anid = 'anid' in element ? element.anid : undefined
        const descriptor: ChartCanvasElement | undefined = anid === 'line' ? { kind: 'axis', axisId: axis.axisId, part: 'line' }
          : typeof anid === 'string' && anid.startsWith('label_') ? { kind: 'axis', axisId: axis.axisId, part: 'label' }
            : typeof anid === 'string' && anid.startsWith('tick_') ? { kind: 'tick', axisId: axis.axisId }
              : typeof anid === 'string' && (anid.startsWith('line_') || anid.startsWith('minor_line_')) ? { kind: 'gridLine', axisId: axis.axisId } : undefined
        if (descriptor) this.tag(element, descriptor)
      })
    }
    const bindings = new Map(runtime.series.map(entry => [entry.runtimeId, entry]))
    model.eachSeries(series => {
      const entry = bindings.get(series.id)
      if (!entry) return
      if ('items' in entry) {
        const data = series.getData()
        data.eachItemGraphicEl((element, index) => {
          const descriptor = readChartCanvasElement(entry.items[data.getRawIndex(index)])
          if (!descriptor) return
          this.tag(element, descriptor)
          const label: ChartCanvasElement = descriptor.kind === 'dataPoint' ? { ...descriptor, kind: 'dataLabel' } : descriptor
          const text = element.getTextContent()
          if (text) this.tag(text, label)
          element.traverse(child => { const attached = child.getTextContent(); if (attached) this.tag(attached, label) })
        })
        return
      }
      if ('directEdit' in entry) {
        const descriptor: ChartCanvasElement = { kind: 'mark', directEdit: entry.directEdit }
        this.tag(native.getViewOfSeriesModel(series).group, descriptor)
        series.getData().eachItemGraphicEl(element => {
          this.tag(element, descriptor)
          const text = element.getTextContent()
          if (text) this.tag(text, descriptor)
          element.traverse(child => { const attached = child.getTextContent(); if (attached) this.tag(attached, descriptor) })
        })
        return
      }
      const descriptor: ChartCanvasElement = entry.seriesMark ? { kind: 'mark', directEdit: entry.seriesMark } : { kind: 'series', binding: entry.binding }
      this.tag(native.getViewOfSeriesModel(series).group, descriptor)
      const data = series.getData()
      data.eachItemGraphicEl((element, index) => {
        const dataIndex = entry.dataIndices[data.getRawIndex(index)]
        if (entry.seriesOnly || dataIndex === undefined) { this.tag(element, descriptor); return }
        const sliceMark = entry.pieSliceMarks?.[dataIndex]
        const sliceElement = sliceMark?.sourcePointIndex === dataIndex && sliceMark.sourceField === entry.binding.field
          && sliceMark.sourceName === entry.binding.sourceName ? readChartCanvasElement({ kind: 'mark', directEdit: sliceMark }) : undefined
        this.tag(element, sliceElement ?? { kind: 'dataPoint', binding: entry.binding, dataIndex })
        const label: ChartCanvasElement = entry.pieLabels ? { kind: 'mark', directEdit: { kind: 'pieStyle' } } : { kind: 'dataLabel', binding: entry.binding, dataIndex }
        const text = element.getTextContent()
        if (text) this.tag(text, label)
        const guide = element.getTextGuideLine()
        if (guide) this.tag(guide, label)
        // Line/scatter symbols store attached text on their child path, while
        // bars/pie sectors attach it directly to the datum displayable.
        element.traverse(child => { const attached = child.getTextContent(); if (attached) this.tag(attached, label) })
      })
    })
    const names = chartNativeLegendNames(option)
    for (const root of instance.getZr().storage.getRoots()) root.traverse(element => {
      const authored = authoredGraphics.get(String(element.id))
      if (authored) this.tag(element, authored)
      const legend = chartNativeLegendHit(element, names)
      if (legend?.kind === 'item') this.tag(element, { kind: 'legend', name: legend.name })
    })
    const frame = { x: 0, y: 0, width, height }
    for (const painted of instance.getZr().storage.getDisplayList(true)) {
      if (!painted.shouldBePainted(width, height, true, true)) continue
      const descriptor = this.descriptor(painted)
      if (!descriptor) continue
      const bounds = transformedBounds(painted, frame)
      if (!bounds || bounds.width <= 0 || bounds.height <= 0) continue
      this.addTarget(descriptor, bounds)
      if (descriptor.kind === 'dataPoint' || descriptor.kind === 'dataLabel') {
        this.addTarget(chartCanvasElementAsSeries(descriptor), bounds)
        const mark = this.seriesMarks.get(descriptor.binding.seriesId)
        if (mark) this.addTarget(mark, bounds)
      } else if (descriptor.kind === 'mark' && descriptor.directEdit.kind === 'seriesStyle') this.addTarget(chartCanvasElementAsSeries(descriptor), bounds)
    }
  }
  private tag(element: NativeElement, descriptor: ChartCanvasElement): void { this.descriptors.set(element, descriptor) }
  private descriptor(element: NativeElement): ChartCanvasElement | undefined {
    let current: NativeElement | undefined = element
    while (current) {
      const result = this.descriptors.get(current)
      if (result) return result
      current = parentElement(current)
    }
    return undefined
  }
  private addTarget(element: ChartCanvasElement, bounds: RenderRect): void {
    const key = chartCanvasElementKey(element), previous = this.targets.get(key)
    this.targets.set(key, { key, element, bounds: union(previous?.bounds, bounds) })
  }
  hit(point?: ChartVector, seriesOnly = false): ChartCanvasElementTarget | undefined {
    if (!point || !Number.isFinite(point.x) || !Number.isFinite(point.y)) return undefined
    const painted = this.instance.getZr().findHover(point.x, point.y).topTarget
    const descriptor = painted && this.descriptor(painted)
    if (!descriptor) return undefined
    const element = seriesOnly ? chartCanvasElementAsSeries(descriptor) : descriptor, target = this.target(element)
    // One legend selection outlines the whole legend, but the actual item hit
    // still retains its native name rather than the last item in the union.
    return target ? { ...target, element } : undefined
  }
  target(element: ChartCanvasElement): ChartCanvasElementTarget | undefined { return this.targets.get(chartCanvasElementKey(element)) }
  list(): ChartCanvasElementTarget[] { return Array.from(this.targets.values()) }
}
