import { execFileSync } from 'node:child_process'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import ts from 'typescript'

// Callable identity is separate from formula implementation/acceptance counts.
const commit = 'eaf4cfa04fabdbcfc922c692f3450459f8a29546'
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const reference = path.resolve(process.argv[2] ?? path.join(root, '..', 'univer'))
const git = (...args) => execFileSync('git', ['-C', reference, ...args], { encoding: 'utf8', maxBuffer: 16 * 1024 * 1024 })
if (git('rev-parse', 'HEAD').trim() !== commit) throw new Error('Reference must remain at the fixed Univer v1.6.0 commit.')
const files = git('ls-tree', '-r', '--name-only', commit, '--', 'packages/engine-formula/src/functions')
  .trim().split(/\r?\n/).filter(file => file.endsWith('/function-names.ts')).sort()
const names = new Set()
for (const file of files) {
  const text = git('show', `${commit}:${file}`)
  const source = ts.createSourceFile(file, text, ts.ScriptTarget.Latest, true)
  for (const statement of source.statements) if (ts.isEnumDeclaration(statement)) {
    for (const member of statement.members) {
      if (!member.initializer || !ts.isStringLiteral(member.initializer)) throw new Error(`${file}: a function name is not a static string.`)
      const name = member.initializer.text
      if (!/^[A-Z][A-Z0-9_.]*$/.test(name)) throw new Error(`${file}: invalid callable identity ${name}.`)
      names.add(name)
    }
  }
}
if (!files.length || !names.size) throw new Error('The fixed reference contains no function-name enums.')
const values = [...names].sort()
const output = [
  '//! Generated by scripts/generate-formula-builtin-names.mjs.',
  `//! Univer v1.6.0 @ ${commit}; ${files.length} function-name files.`,
  '//! Identity prevents defined-name remapping from hijacking built-in calls.',
  '//! This table does not register evaluators or prove function completion.',
  '',
  'pub(super) fn contains(name: &str) -> bool { NAMES.binary_search(&name).is_ok() }',
  '',
  'const NAMES: &[&str] = &[',
  ...values.map(name => `    "${name}",`),
  '];',
  '',
].join('\n')
fs.writeFileSync(path.join(root, 'crates/office-writer/src/xlsx_formula_builtin_names.rs'), output)
process.stdout.write(`Generated ${values.length} callable identities from ${files.length} fixed source files.\n`)
